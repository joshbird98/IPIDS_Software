KEEP_BACKUPS = 50
LARGE_CHANGE_FACTOR = 3.0
NOT_EDITABLE = {"system_tags.json",            # generated by src/utils/build_registry.py
                "workspace_profiles.json",     # viewer state (per machine)
                "plot_settings.json"}          # viewer state (per machine)
REGISTRY_INPUTS = {"fault_config.json", "mpd_config.json", "vac_gauges_config.json", "magnet_config.json",
                   "steerer_magnet_config.json", "smu_config.json", "plc_config.json"}
FALLBACK_ENCODING = "cp1252"                   # what Notepad's "ANSI" means on the lab PC


class ConfigError(ValueError):
    """The file can't be read as JSON (the message says where)."""


@dataclass
class SaveResult:
    saved: bool = False
    path: str = ""
    backup: Optional[str] = None
    problems: list = field(default_factory=list)      # why nothing was written
    committed: bool = False
    git: str = ""                                     # commit id, or why there is no commit
    error: str = ""                                   # write / after_write failure (backup restored)


# ============================================================================ files
def config_files(config_dir: str = None) -> list:
    config_dir = config_dir or paths.CONFIG_DIR
    try:
        names = os.listdir(config_dir)
    except OSError:
        return []
    return sorted(n for n in names if n.endswith(".json") and n not in NOT_EDITABLE)


def read_text(path: str) -> tuple:
    """(text, encoding): UTF-8 (a byte-order mark is dropped - the services' JSON readers choke on
    it), else the Windows code page (raises OSError)."""
    with open(path, "rb") as f:
        raw = f.read()
    if raw.startswith(b"\xef\xbb\xbf"):
        raw = raw[3:]
    for encoding in ("utf-8", FALLBACK_ENCODING, "latin-1"):     # latin-1 decodes any bytes
        try:
            return raw.decode(encoding), encoding
        except UnicodeDecodeError:
            continue


def read_path(path: str, label: str = None):
    """The JSON in `path` (raises ConfigError with what is wrong)."""
    label = label or os.path.basename(path)
    try:
        text, _ = read_text(path)
    except OSError as e:
        raise ConfigError(f"{label}: {e.strerror or e}") from e
    try:
        return json.loads(text)
    except ValueError as e:
        raise ConfigError(f"{label} is not valid JSON: {e}") from e


def read(name: str, config_dir: str = None):
    return read_path(os.path.join(config_dir or paths.CONFIG_DIR, name), name)


def load(name: str, config_dir: str = None):
    """(data, problems). Raises ConfigError if the file can't be parsed at all."""
    data = read(name, config_dir)
    return data, check(name, data)


def _write_atomic(path: str, raw: bytes):
    tmp = path + ".tmp"
    with open(tmp, "wb") as f:
        f.write(raw)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def _full_text(data, old_text: str) -> str:
    """The whole file, indented like the old one and with its line endings. ASCII only (other
    characters as \\u escapes): the services on the Windows lab PC open these files in the
    default code page."""
    lines = old_text.splitlines()
    second = lines[1] if len(lines) > 1 else ""
    indent = len(second) - len(second.lstrip(" "))
    text = json.dumps(data, indent=indent if indent in (2, 4) else 2, ensure_ascii=True) + "\n"
    return text.replace("\n", "\r\n") if "\r\n" in old_text else text


def same_json(a, b) -> bool:
    """Equal with the same JSON types (1 and 1.0, or 1 and true, are different here)."""
    if type(a) is not type(b):
        return False
    if isinstance(a, dict):
        return a.keys() == b.keys() and all(same_json(a[k], b[k]) for k in a)
    if isinstance(a, list):
        return len(a) == len(b) and all(same_json(x, y) for x, y in zip(a, b))
    return a == b


# ---------------------------------------------------------------- minimal-diff writing
_WS = re.compile(r"[ \t\n\r]*")
_NUM = re.compile(r"-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][-+]?\d+)?")


def value_spans(text: str) -> dict:
    """{path: (start, end)} of every scalar value in a JSON text; paths are tuples of keys and
    list indices, as in apply_edits(). Raises ValueError if the text isn't plain JSON."""
    spans = {}

    def skip(i):
        return _WS.match(text, i).end()

    def value(i, path):
        i = skip(i)
        c = text[i]
        if c == "{":
            i = skip(i + 1)
            if text[i] == "}":
                return i + 1
            while True:
                if text[i] != '"':
                    raise ValueError(f"expected a key at {i}")
                key, i = json.decoder.scanstring(text, i + 1)
                i = skip(i)
                if text[i] != ":":
                    raise ValueError(f"expected ':' at {i}")
                i = skip(value(i + 1, path + (key,)))
                if text[i] == ",":
                    i = skip(i + 1)
                elif text[i] == "}":
                    return i + 1
                else:
                    raise ValueError(f"expected ',' or '}}' at {i}")
        if c == "[":
            i = skip(i + 1)
            if text[i] == "]":
                return i + 1
            n = 0
            while True:
                i = skip(value(i, path + (n,)))
                n += 1
                if text[i] == ",":
                    i += 1
                elif text[i] == "]":
                    return i + 1
                else:
                    raise ValueError(f"expected ',' or ']' at {i}")
        if c == '"':
            _, end = json.decoder.scanstring(text, i + 1)
        else:
            lit = next((w for w in ("true", "false", "null") if text.startswith(w, i)), None)
            m = None if lit else _NUM.match(text, i)
            if lit is None and m is None:
                raise ValueError(f"unexpected character at {i}")
            end = i + len(lit) if lit else m.end()
        spans[path] = (i, end)
        return end

    try:
        end = value(0, ())
    except IndexError:
        raise ValueError("unexpected end of the text") from None
    if skip(end) != len(text):
        raise ValueError(f"unexpected text after the end, at {end}")
    return spans


def _get(data, path):
    for key in path:
        data = data[key]
    return data


def patched_text(text: str, new_data) -> Optional[str]:
    """`text` with just the changed values rewritten, or None if the structure differs."""
    try:
        old_data = json.loads(text)
        spans = value_spans(text)
        edits = []
        for path_, (a, b) in spans.items():
            old_v, new_v = _get(old_data, path_), _get(new_data, path_)
            if old_v != new_v or type(old_v) is not type(new_v):
                edits.append((a, b, json.dumps(new_v, ensure_ascii=True)))
    except (ValueError, KeyError, IndexError, TypeError):
        return None
    for a, b, replacement in sorted(edits, reverse=True):
        text = text[:a] + replacement + text[b:]
    try:
        return text if json.loads(text) == new_data else None
    except ValueError:
        return None


# ---------------------------------------------------------------- backups
def backup_dir(config_dir: str = None) -> str:
    return os.path.join(config_dir or paths.CONFIG_DIR, "backups")


def _backup_order(filename: str):
    m = re.search(r"\.(\d{8}-\d{6})(?:-(\d+))?\.json$", filename)
    return (m[1], int(m[2] or 0)) if m else ("", 0)


def backups(name: str, config_dir: str = None) -> list:
    """Backups of `name`, newest first (two in the same second: the later one, '-1', first)."""
    folder = backup_dir(config_dir)
    stem = name[:-5] if name.endswith(".json") else name
    try:
        found = [f for f in os.listdir(folder)
                 if re.fullmatch(re.escape(stem) + r"\.\d{8}-\d{6}(-\d+)?\.json", f)]
    except OSError:
        return []
    return [os.path.join(folder, f) for f in sorted(found, key=_backup_order, reverse=True)]


def backup_time(path: str) -> str:
    """'2026-10-18 19:35:12' from a backup's file name."""
    m = re.search(r"\.(\d{4})(\d{2})(\d{2})-(\d{2})(\d{2})(\d{2})", os.path.basename(path))
    return f"{m[1]}-{m[2]}-{m[3]} {m[4]}:{m[5]}:{m[6]}" if m else os.path.basename(path)


def make_backup(name: str, config_dir: str = None, clock=time.time) -> Optional[str]:
    """Copy the current file into backups/ (None if there is no current file). Old ones are pruned."""
    src = os.path.join(config_dir or paths.CONFIG_DIR, name)
    if not os.path.exists(src):
        return None
    folder = backup_dir(config_dir)
    os.makedirs(folder, exist_ok=True)
    stem = name[:-5] if name.endswith(".json") else name
    base = f"{stem}.{time.strftime('%Y%m%d-%H%M%S', time.localtime(clock()))}"
    dst, n = os.path.join(folder, base + ".json"), 1
    while os.path.exists(dst):
        dst, n = os.path.join(folder, f"{base}-{n}.json"), n + 1
    shutil.copy2(src, dst)
    for old in backups(name, config_dir)[KEEP_BACKUPS:]:
        try:
            os.remove(old)
        except OSError as e:
            log.warning("Could not prune old backup %s: %s", old, e)
    return dst


# ============================================================================ git
def git_commit(path: str, message: str, run=subprocess.run) -> tuple:
    """Commit just this file. (True, short id) or (False, why not)."""
    folder = os.path.dirname(os.path.abspath(path))

    def git(*args, ident=()):
        return run(["git", "-C", folder, *ident, *args], capture_output=True, text=True, timeout=20)

    try:
        if git("rev-parse", "--is-inside-work-tree").stdout.strip() != "true":
            return False, "config folder is not in a git work tree"
        if git("check-ignore", "-q", path).returncode == 0:
            return False, "file is ignored by git"
        ident = () if git("config", "user.email").stdout.strip() else \
            ("-c", "user.name=SINDIE HMI", "-c", "user.email=sindie-hmi@localhost")
        literal = ":(literal)" + os.path.abspath(path)      # the name is a path, never a pattern
        r = git("add", "--", literal)
        if r.returncode:
            return False, (r.stderr or r.stdout).strip() or "git add failed"
        r = git("commit", "-m", message, "--", literal, ident=ident)
        if r.returncode:
            text = (r.stdout + r.stderr).strip()
            return False, "no change to commit" if "nothing to commit" in text or "no changes added" in text \
                else (text.splitlines()[-1] if text else "git commit failed")
        return True, git("rev-parse", "--short", "HEAD").stdout.strip()
    except (OSError, subprocess.SubprocessError) as e:
        return False, f"git not available ({e})"


# ============================================================================ save
def save(name: str, data, original=None, reason: str = "", config_dir: str = None,
         after_write: Callable[[], Optional[str]] = None, commit: bool = True, run=subprocess.run,
         clock=time.time, expected=None, raw: bytes = None) -> SaveResult:
    """Check, back up, write, run after_write (returns an error text or None), commit. See module doc.

    original: the structure `data` must keep (None: only the file's own rules are checked).
    expected: what the file on disk must still contain (None: not checked).
    raw: write exactly these bytes (they must hold `data`) - used to put a backup back as it was."""
    config_dir = config_dir or paths.CONFIG_DIR
    path = os.path.join(config_dir, name)
    result = SaveResult(path=path)
    result.problems = check(name, data, original)
    if result.problems:
        return result
    try:
        old_text, encoding = read_text(path) if os.path.exists(path) else ("", "utf-8")
    except OSError as e:
        result.error = f"could not read {name}: {e}"
        return result
    if expected is not None:
        try:
            on_disk = json.loads(old_text)
        except ValueError:
            on_disk = None
        if not same_json(on_disk, expected):
            result.problems = [f"{name} was changed on disk since it was opened here (edited by hand, or a git "
                               "pull) - open it again and make the change again, so that change isn't undone"]
            return result
    try:
        if raw is not None:
            new_raw = raw
        else:
            new_text = (patched_text(old_text, data) if old_text else None) or _full_text(data, old_text)
            new_raw = new_text.encode(encoding)
    except UnicodeEncodeError as e:
        result.error = f"could not write {name}: {e}"
        return result
    try:
        result.backup = make_backup(name, config_dir, clock)
        _write_atomic(path, new_raw)
    except OSError as e:
        result.error = f"could not write {name}: {e}"
        return result
    if after_write is not None:
        error = after_write()
        if error:
            result.error = error
            if result.backup:
                try:
                    with open(result.backup, "rb") as f:
                        previous = f.read()
                    tmp = path + ".tmp"
                    with open(tmp, "wb") as f:
                        f.write(previous)
                    os.replace(tmp, path)
                    result.error += " - the previous file was put back"
                except OSError as e:
                    result.error += f" - AND the previous file could not be put back ({e}); it is in {result.backup}"
            return result
    result.saved = True
    if commit:
        message = f"Config editor: {name}" + (f" - {reason.strip()}" if reason.strip() else "")
        result.committed, result.git = git_commit(path, message, run=run)
    else:
        result.git = "git commit switched off"
    return result


def restore(name: str, backup_path: str, **kw) -> SaveResult:
    """Make a backup the current file again, byte for byte (checked, and the current file backed
    up, like any save)."""
    try:
        with open(backup_path, "rb") as f:
            raw = f.read()
        text, _ = read_text(backup_path)
        data = json.loads(text)
    except (OSError, ValueError) as e:
        return SaveResult(error=f"could not read {backup_path}: {e}")
    kw.setdefault("reason", f"put back the version from before {backup_time(backup_path)}")
    return save(name, data, raw=raw, **kw)


def rebuild_registry(timeout_s: float = 120.0, run=subprocess.run) -> Optional[str]:
    """Run src/utils/build_registry.py. None if it worked, else what went wrong."""
    import sys
    script = os.path.join(paths.PROJECT_ROOT, "src", "utils", "build_registry.py")
    try:
        r = run([sys.executable, script], capture_output=True, text=True, timeout=timeout_s)
    except (OSError, subprocess.SubprocessError) as e:
        return f"rebuilding system_tags.json failed: {e}"
    if r.returncode:
        tail = (r.stderr or r.stdout or "").strip()[-800:]
        return f"rebuilding system_tags.json failed (exit {r.returncode}): {tail}"
    return None


# ============================================================================ differences
def diff(old, new, where: str = "") -> list:
    """Human-readable changes, e.g. ['max_current: 95.0 -> 90.0']."""
    out = []
    if isinstance(old, dict) and isinstance(new, dict):
        for k in old:
            if k not in new:
                out.append(f"{join_path(where, k)}: removed")
        for k in new:
            if k not in old:
                out.append(f"{join_path(where, k)}: added {short_json(new[k])}")
            else:
                out.extend(diff(old[k], new[k], join_path(where, k)))
    elif isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        for i, (a, b) in enumerate(zip(old, new)):
            out.extend(diff(a, b, f"{where}[{i}]"))
    elif old != new or type(old) is not type(new):
        out.append(f"{where or '(file)'}: {short_json(old)} -> {short_json(new)}")
    return out


def _number(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v)


def large_changes(old, new, where: str = "", factor: float = LARGE_CHANGE_FACTOR) -> list:
    """Numbers that change by more than `factor`, or change sign: the slips a range check can't
    catch, like 95.0 typed as 950. E.g. ['max_current: 95 -> 950 (x10)']. Not flagged: changes to
    or from zero (no ratio to judge) and small whole numbers (counts, priorities, ranks 0..10)."""
    out = []
    if isinstance(old, dict) and isinstance(new, dict):
        for k in old:
            if k in new:
                out += large_changes(old[k], new[k], join_path(where, k), factor)
    elif isinstance(old, list) and isinstance(new, list):
        for i, (a, b) in enumerate(zip(old, new)):
            out += large_changes(a, b, f"{where}[{i}]", factor)
    elif _number(old) and _number(new) and old != new and old != 0 and new != 0:
        if all(isinstance(v, int) and abs(v) <= 10 for v in (old, new)):
            return out
        label = f"{where}: {old:g} -> {new:g}"
        if (old > 0) != (new > 0):
            out.append(label + " (sign change)")
        else:
            ratio = abs(new / old)
            if ratio > factor or ratio < 1 / factor:
                out.append(label + (f" (x{ratio:.3g})" if ratio > 1 else f" (/{1 / ratio:.3g})"))
    return out


def apply_edits(original, leaves: dict):
    """A copy of `original` with leaf values replaced. leaves: {path tuple: value}."""
    data = copy.deepcopy(original)
    for path_, value in leaves.items():
        node = data
        for key in path_[:-1]:
            node = node[key]
        node[path_[-1]] = value
    return data
