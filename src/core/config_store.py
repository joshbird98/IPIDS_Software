"""Changing config files from the HMI: checked, backed up, and saved as this machine's lab settings.

    data, problems = load("magnet_config.json")       # problems: what the services would trip over
    result = save("magnet_config.json", new_data, original=data, expected=data, reason="new PSU")

A config file as the system uses it is the repository's file in config/ with this machine's lab
settings, config/lab/<name>.json, on top (src/core/lab_config.py). The repository's files change
only with software updates; what is changed here goes into the lab file, which isn't in git, so
an update never overwrites it and it never stands in an update's way. Nothing here commits to git:
the lab PC's git work tree stays as the updates leave it.

save():
  1. check() the new contents - wrong types, missing keys, limits the wrong way round or out of
     range, duplicate ports... Any problem and nothing is written (SaveResult.problems says why).
     With `expected`, the file as the system uses it must still be what the change was made
     against: if it changed meanwhile (edited by hand, or an update), nothing is written rather
     than silently undoing that change.
  2. the file as the system used it is written to config/backups/<name>.<YYYYmmdd-HHMMSS>.json (the
     newest KEEP_BACKUPS of each file are kept; backups are not in git),
  3. the lab file is written - only what differs from the repository's file - to a temporary file
     and swapped in, so a crash never leaves half a file,
  4. `after_write` runs (the HMI rebuilds system_tags.json there); if it fails, the previous lab
     file is put back and the save reports the failure - the services never see a config whose
     registry could not be built.

Files are read as UTF-8, or in the Windows code page if they aren't. The checks themselves are in
config_checks.py. The minimal-diff writing below (patched_text) is the recipe files': a recipe saved
from the builder keeps its layout, and a change of one value is one line.
"""
