"""Changing config files from the HMI: checked, backed up, written whole, and committed to git.

    data, problems = load("magnet_config.json")       # problems: what the services would trip over
    result = save("magnet_config.json", new_data, original=data, expected=data, reason="new PSU")

save():
  1. check() the new contents - wrong types, missing keys, limits the wrong way round or out of
     range, duplicate ports... Any problem and nothing is written (SaveResult.problems says why).
     With `expected`, the file on disk must still be what the change was made against: if someone
     edited it (or a git pull changed it) meanwhile, nothing is written rather than silently
     undoing their change.
  2. the current file is copied to config/backups/<name>.<YYYYmmdd-HHMMSS>.json (the newest
     KEEP_BACKUPS of each file are kept; backups are not in git),
  3. the new file is written to a temporary file and swapped in, so a crash never leaves half a file,
  4. `after_write` runs (the HMI rebuilds system_tags.json there); if it fails, the backup is put
     back and the save reports the failure - the services never see a config whose registry
     could not be built,
  5. the file is committed to git when config/ is inside a git work tree (best effort: the result
     says what happened; the control PC then has local commits - pull with --rebase).

Only the values that changed are rewritten in the file's text, so its layout, its other numbers
as typed ("200e-6") and its comments stay as they were, and a change of one number is one line in
git. (If that isn't possible - a different structure - the whole file is written, keeping its
indentation.) Files are read as UTF-8, or in the Windows code page the services use if they aren't
UTF-8, and written back the same way. The checks themselves are in config_checks.py.
"""
