"""Changing config files from the HMI: checked, backed up, written whole, and committed to git.

    data, problems = load("magnet_config.json")       # problems: what the services would trip over
    result = save("magnet_config.json", new_data, original=data, reason="new PSU")

save():
  1. check() the new contents - wrong types, missing keys, limits the wrong way round, duplicate
     ports... Any problem and nothing is written (SaveResult.problems says why).
  2. the current file is copied to config/backups/<name>.<YYYYmmdd-HHMMSS>.json (the newest
     KEEP_BACKUPS of each file are kept; backups are not in git),
  3. the new file is written to a temporary file and swapped in, so a crash never leaves half a file,
  4. `after_write` runs (the HMI rebuilds system_tags.json there); if it fails, the backup is put
     back and the save reports the failure - the services never see a config whose registry
     could not be built,
  5. the file is committed to git when config/ is inside a git work tree (best effort: the result
     says what happened; the control PC then has local commits - pull with --rebase).

Values keep their JSON types (a float stays a float, an empty list stays a list) and the file
keeps its indentation, so a save that changes one number changes one line in git. The checks
themselves are in config_checks.py.
"""
import copy
import json
import logging
import os
import re
import shutil
import subprocess
import time
from dataclasses import dataclass, field
from typing import Callable, Optional

from src.core import paths
from src.core.config_checks import is_devices, join_path, short_json, check

log = logging.getLogger("config_store")

KEEP_BACKUPS = 50
NOT_EDITABLE = {"system_tags.json",            # generated by src/utils/build_registry.py
                "workspace_profiles.json",     # viewer state (per machine)
                "plot_settings.json"}          # viewer state (per machine)
REGISTRY_INPUTS = {"fault_config.json", "mpd_config.json", "vac_gauges_config.json", "magnet_config.json",
                   "steerer_magnet_config.json", "smu_config.json", "plc_config.json"}


class ConfigError(ValueError):
    """The file can't be read as JSON (the message says where)."""


@dataclass
class SaveResult:
    saved: bool = False
    path: str = ""
    backup: Optional[str] = None
    problems: list = field(default_factory=list)      # why nothing was written
    committed: bool = False
    git: str = ""                                     # commit id, or why there is no commit
    error: str = ""                                   # write / after_write failure (backup restored)


# ============================================================================ files
def config_files(config_dir: str = None) -> list:
    config_dir = config_dir or paths.CONFIG_DIR
    try:
        names = os.listdir(config_dir)
    except OSError:
        return []
    return sorted(n for n in names if n.endswith(".json") and n not in NOT_EDITABLE)


def read(name: str, config_dir: str = None):
    path = os.path.join(config_dir or paths.CONFIG_DIR, name)
    try:
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
    except OSError as e:
        raise ConfigError(f"{name}: {e.strerror or e}") from e
    try:
        return json.loads(text)
    except ValueError as e:
        raise ConfigError(f"{name} is not valid JSON: {e}") from e


def load(name: str, config_dir: str = None):
    """(data, problems). Raises ConfigError if the file can't be parsed at all."""
    data = read(name, config_dir)
    return data, check(name, data)


def _indent_of(path: str) -> int:
    try:
        with open(path, "r", encoding="utf-8") as f:
            f.readline()
            second = f.readline()
    except OSError:
        return 2
    n = len(second) - len(second.lstrip(" "))
    return n if n in (2, 4) else 2


def _write_atomic(path: str, data, indent: int):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        # ASCII only (other characters as \u escapes): services on the Windows lab PC open these
        # files with the default code page, which can't decode every UTF-8 byte
        json.dump(data, f, indent=indent, ensure_ascii=True)
        f.write("\n")
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def backup_dir(config_dir: str = None) -> str:
    return os.path.join(config_dir or paths.CONFIG_DIR, "backups")


def backups(name: str, config_dir: str = None) -> list:
    """Backups of `name`, newest first."""
    folder = backup_dir(config_dir)
    stem = name[:-5] if name.endswith(".json") else name
    try:
        found = [f for f in os.listdir(folder) if f.startswith(stem + ".") and f.endswith(".json")
                 and re.fullmatch(re.escape(stem) + r"\.\d{8}-\d{6}(-\d+)?\.json", f)]
    except OSError:
        return []
    return [os.path.join(folder, f) for f in sorted(found, reverse=True)]


def backup_time(path: str) -> str:
    """'2026-10-18 19:35:12' from a backup's file name."""
    m = re.search(r"\.(\d{4})(\d{2})(\d{2})-(\d{2})(\d{2})(\d{2})", os.path.basename(path))
    return f"{m[1]}-{m[2]}-{m[3]} {m[4]}:{m[5]}:{m[6]}" if m else os.path.basename(path)


def make_backup(name: str, config_dir: str = None, clock=time.time) -> Optional[str]:
    """Copy the current file into backups/ (None if there is no current file). Old ones are pruned."""
    src = os.path.join(config_dir or paths.CONFIG_DIR, name)
    if not os.path.exists(src):
        return None
    folder = backup_dir(config_dir)
    os.makedirs(folder, exist_ok=True)
    stem = name[:-5] if name.endswith(".json") else name
    base = f"{stem}.{time.strftime('%Y%m%d-%H%M%S', time.localtime(clock()))}"
    dst, n = os.path.join(folder, base + ".json"), 1
    while os.path.exists(dst):
        dst, n = os.path.join(folder, f"{base}-{n}.json"), n + 1
    shutil.copy2(src, dst)
    for old in backups(name, config_dir)[KEEP_BACKUPS:]:
        try:
            os.remove(old)
        except OSError as e:
            log.warning("Could not prune old backup %s: %s", old, e)
    return dst


# ============================================================================ git
def git_commit(path: str, message: str, run=subprocess.run) -> tuple:
    """Commit just this file. (True, short id) or (False, why not)."""
    folder = os.path.dirname(os.path.abspath(path))

    def git(*args, ident=()):
        return run(["git", "-C", folder, *ident, *args], capture_output=True, text=True, timeout=20)

    try:
        if git("rev-parse", "--is-inside-work-tree").stdout.strip() != "true":
            return False, "config folder is not in a git work tree"
        if git("check-ignore", "-q", path).returncode == 0:
            return False, "file is ignored by git"
        ident = () if git("config", "user.email").stdout.strip() else \
            ("-c", "user.name=SINDIE HMI", "-c", "user.email=sindie-hmi@localhost")
        r = git("add", "--", path)
        if r.returncode:
            return False, (r.stderr or r.stdout).strip() or "git add failed"
        r = git("commit", "-m", message, "--", path, ident=ident)
        if r.returncode:
            text = (r.stdout + r.stderr).strip()
            return False, "no change to commit" if "nothing to commit" in text or "no changes added" in text \
                else (text.splitlines()[-1] if text else "git commit failed")
        return True, git("rev-parse", "--short", "HEAD").stdout.strip()
    except (OSError, subprocess.SubprocessError) as e:
        return False, f"git not available ({e})"


# ============================================================================ save
def save(name: str, data, original=None, reason: str = "", config_dir: str = None,
         after_write: Callable[[], Optional[str]] = None, commit: bool = True, run=subprocess.run,
         clock=time.time) -> SaveResult:
    """Check, back up, write, run after_write (returns an error text or None), commit. See module doc."""
    config_dir = config_dir or paths.CONFIG_DIR
    path = os.path.join(config_dir, name)
    result = SaveResult(path=path)
    result.problems = check(name, data, original)
    if result.problems:
        return result
    indent = _indent_of(path)
    try:
        result.backup = make_backup(name, config_dir, clock)
        _write_atomic(path, data, indent)
    except (OSError, TypeError, ValueError) as e:
        result.error = f"could not write {name}: {e}"
        return result
    if after_write is not None:
        error = after_write()
        if error:
            result.error = error
            if result.backup:
                try:
                    shutil.copy2(result.backup, path)
                    result.error += " - the previous file was put back"
                except OSError as e:
                    result.error += f" - AND the previous file could not be put back ({e}); it is in {result.backup}"
            return result
    result.saved = True
    if commit:
        message = f"Config editor: {name}" + (f" - {reason.strip()}" if reason.strip() else "")
        result.committed, result.git = git_commit(path, message, run=run)
    else:
        result.git = "git commit switched off"
    return result


def restore(name: str, backup_path: str, **kw) -> SaveResult:
    """Make a backup the current file again (checked, and the current file backed up, like any save)."""
    try:
        with open(backup_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as e:
        return SaveResult(error=f"could not read {backup_path}: {e}")
    kw.setdefault("reason", f"restored the version of {backup_time(backup_path)}")
    return save(name, data, **kw)


def rebuild_registry(timeout_s: float = 120.0, run=subprocess.run) -> Optional[str]:
    """Run src/utils/build_registry.py. None if it worked, else what went wrong."""
    import sys
    script = os.path.join(paths.PROJECT_ROOT, "src", "utils", "build_registry.py")
    try:
        r = run([sys.executable, script], capture_output=True, text=True, timeout=timeout_s)
    except (OSError, subprocess.SubprocessError) as e:
        return f"rebuilding system_tags.json failed: {e}"
    if r.returncode:
        tail = (r.stderr or r.stdout or "").strip()[-800:]
        return f"rebuilding system_tags.json failed (exit {r.returncode}): {tail}"
    return None


# ============================================================================ differences
def diff(old, new, where: str = "") -> list:
    """Human-readable changes, e.g. ['max_current: 95.0 -> 90.0']."""
    out = []
    if isinstance(old, dict) and isinstance(new, dict):
        for k in old:
            if k not in new:
                out.append(f"{join_path(where, k)}: removed")
        for k in new:
            if k not in old:
                out.append(f"{join_path(where, k)}: added {short_json(new[k])}")
            else:
                out.extend(diff(old[k], new[k], join_path(where, k)))
    elif isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        for i, (a, b) in enumerate(zip(old, new)):
            out.extend(diff(a, b, f"{where}[{i}]"))
    elif old != new or type(old) is not type(new):
        out.append(f"{where or '(file)'}: {short_json(old)} -> {short_json(new)}")
    return out


def renamed_diff(old, new) -> list:
    """diff() that reports a renamed device key as a rename, not as a removal plus an addition."""
    return diff(_rename_like(old, new), new) + _renames(old, new, "")


def _renames(old, new, where):
    out = []
    if isinstance(old, dict) and isinstance(new, dict):
        if is_devices(where) and len(old) == len(new):
            out += [f"{join_path(where, a)}: renamed to {b!r}" for a, b in zip(old, new) if a != b]
        for k in old:
            if k in new:
                out += _renames(old[k], new[k], join_path(where, k))
    elif isinstance(old, list) and isinstance(new, list):
        for i, (a, b) in enumerate(zip(old, new)):
            out += _renames(a, b, f"{where}[{i}]")
    return out


def _rename_like(old, new, where=""):
    """`old` with device keys renamed as in `new`, so diff() compares the values."""
    if isinstance(old, dict) and isinstance(new, dict):
        if is_devices(where) and len(old) == len(new):
            return {b: _rename_like(v, new[b], join_path(where, b)) for (a, v), b in zip(old.items(), new)}
        return {k: (_rename_like(v, new[k], join_path(where, k)) if k in new else v) for k, v in old.items()}
    if isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        return [_rename_like(a, b, f"{where}[{i}]") for i, (a, b) in enumerate(zip(old, new))]
    return old


def apply_edits(original, leaves: dict, renames: dict = None):
    """A copy of `original` with leaf values replaced and device keys renamed.

    leaves: {path tuple: value}; renames: {path of the device dict: {old key: new key}}.
    Paths use the original keys (renames are applied last, keeping the order)."""
    data = copy.deepcopy(original)
    for path_, value in leaves.items():
        node = data
        for key in path_[:-1]:
            node = node[key]
        node[path_[-1]] = value
    for path_, mapping in sorted((renames or {}).items(), key=lambda kv: -len(kv[0])):
        parent = data
        for key in path_[:-1]:
            parent = parent[key]
        old = parent[path_[-1]] if path_ else data
        new_keys = [mapping.get(k, k) for k in old]
        clash = sorted({str(k) for k in new_keys if new_keys.count(k) > 1})
        if clash:
            raise ValueError(f"{'.'.join(map(str, path_))}: two entries would both be called {', '.join(clash)}")
        renamed = dict(zip(new_keys, old.values()))
        if path_:
            parent[path_[-1]] = renamed
        else:
            data = renamed
    return data
